#!/usr/bin/env python3
"""Prepare (but do not run) the small TSO lemma and partitioned equivalence check.

Run from the repository root. `mode` records the input fingerprint before the
lemma extraction. `eqy` requires that lemma to PASS, then generates auditable
Yosys scripts, observation wrappers, and an EQY configuration.
"""
import argparse
import csv
import hashlib
import json
from pathlib import Path
import re
import subprocess
import sys

from make_miter import STARTUP_RESET_CYCLES, declaration

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
ART = Path("formal/sbuffer/artifacts/DefaultConfig/Sbuffer")
WORK = Path("formal/sbuffer/work/eqy")
PROOF = Path("formal/sbuffer/work/tso-mode")


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("stage", choices=["mode", "eqy"])
    args = parser.parse_args()
    if Path.cwd() != ROOT:
        parser.error("run from the repository root")
    WORK.mkdir(parents=True, exist_ok=True)
    if args.stage == "mode":
        (WORK / "mode-input.json").write_text(json.dumps({
            str(path): digest(path) for path in
            [ART / "tip.il", HERE / "tso_mode.ys", HERE / "tso_mode.sv"]
        }, indent=2) + "\n")
        print("Recorded mode-proof input hashes. Next run:")
        print("yosys -s formal/sbuffer/tso_mode.ys")
        print("sby -d formal/sbuffer/work/tso-mode formal/sbuffer/tso_mode.sby")
        return

    manifest = json.loads((WORK / "mode-input.json").read_text())
    if any(digest(Path(path)) != expected for path, expected in manifest.items()):
        parser.error("mode-proof inputs changed: repeat the mode stage and its proof")
    if not (PROOF / "status").is_file() or (PROOF / "status").read_text().split()[0] != "PASS":
        parser.error("the TSO mode lemma must PASS first")
    for name, path in [("tso_mode.il", WORK / "tso_mode.il"),
                       ("tso_mode.sv", HERE / "tso_mode.sv")]:
        if digest(PROOF / "src" / name) != digest(path):
            parser.error(f"mode proof used a different {name}; rerun it")

    subprocess.run([sys.executable, str(HERE / "make_miter.py")], check=True)
    with (ART / "interface.tsv").open() as stream:
        policies = {row["port"]: row for row in csv.DictReader(stream, delimiter="\t")}

    for side in ("base", "tip"):
        module = json.loads((ART / f"{side}.json").read_text())["modules"][f"Sbuffer_{side}"]
        ports = module["ports"]
        inputs = {n: p for n, p in ports.items()
                  if p["direction"] == "input" and n != "io_csrCtrl_tso_enable"}
        outputs = {n: p for n, p in ports.items() if p["direction"] == "output"}
        lines = [
            "// Generated by prepare_eqy.py. Zero denotes an unobserved payload.",
            "module Sbuffer_observed (",
            ",\n".join("  " + declaration("input wire", n, p) for n, p in inputs.items()) + ",",
            ",\n".join("  " + declaration("output wire", n, p) for n, p in outputs.items()),
            ");", "",
            "  reg boot = 1'b1;",
            "  always @(posedge clock) boot <= 1'b0;",
            f"  reg [{STARTUP_RESET_CYCLES - 1}:0] startup_reset = '1;",
            "  always @(posedge clock) startup_reset <= startup_reset >> 1;",
            "  wire dut_reset = reset || (|startup_reset);",
            "  wire observing = !(|startup_reset) && !reset;",
            "  reg [2:0] history_valid = 3'b000;",
        ]
        # Match the exact query-valid inputs, excluding fields of the uop.
        lanes = [m[1] for n in inputs if (m := re.fullmatch(r"io_forward_(\d+)_valid", n))]
        for lane in lanes:
            lines.append(f"  reg forward_valid_d_{lane} = 1'b0;")
        lines += ["  always @(posedge clock) begin", "    if (dut_reset) begin",
                  "      history_valid <= 3'b000;"]
        lines += [f"      forward_valid_d_{lane} <= 1'b0;" for lane in lanes]
        lines += ["    end else begin", "      history_valid <= {history_valid[1:0], 1'b1};"]
        lines += [f"      forward_valid_d_{lane} <= io_forward_{lane}_valid;" for lane in lanes]
        lines += ["    end", "  end", ""]
        if side == "tip":
            # The lemma starts AFTER the first reset edge. Preserve arbitrary
            # pre-reset mode values on that first edge: they can feed unreset
            # pipeline registers even though observations are disabled then.
            lines += ["  (* anyconst *) reg initial_tsoActive;",
                      "  (* anyconst *) reg initial_tsoTransitioning;"]
        lines += ["  " + declaration("wire", f"raw_{n}", p) + ";" for n, p in outputs.items()]
        lines.append(f"  Sbuffer_{side} dut (")
        connections = []
        for n, p in ports.items():
            signal = ("1'b0" if n == "io_csrCtrl_tso_enable" else
                      "dut_reset" if n == "reset" else
                      n if p["direction"] == "input" else "raw_" + n)
            connections.append(f"    .{n}({signal})")
        if side == "tip":
            connections += ["    .tsoActive(boot && initial_tsoActive)",
                            "    .tsoTransitioning(boot && initial_tsoTransitioning)"]
        lines += [",\n".join(connections), "  );", ""]
        for n, p in outputs.items():
            policy = policies[n]["policy"]
            if policy == "skip":
                lines.append(f"  assign {n} = '0; // {policies[n]['condition_or_reason']}")
            elif policy == "cache_data":
                for byte in range(len(p["bits"]) // 8):
                    lines.append(f"  assign {n}[{8*byte} +: 8] = observing && raw_io_dcache_req_valid && raw_io_dcache_req_bits_mask[{byte}] ? raw_{n}[{8*byte} +: 8] : 8'b0;")
            else:
                qualifier = "1'b1" if policy == "always" else policy
                qualifier = qualifier.replace("base_", "raw_").replace("tip_", "raw_")
                lines.append(f"  assign {n} = observing && ({qualifier}) ? raw_{n} : '0;")
        lines += ["endmodule", ""]
        (WORK / f"{side}_observed.sv").write_text("\n".join(lines))
        script = [f"read_rtlil {ART}/{side}.il", f"cd Sbuffer_{side}"]
        if side == "tip":
            script += [
                "# The wrapper preserves arbitrary startup values, then uses",
                "# the separately proven zero values after the reset edge.",
                "expose -input w:tsoActive w:tsoTransitioning",
            ]
        script += ["select -clear", "opt -full",
                   f"read_verilog -formal -sv {WORK}/{side}_observed.sv",
                   "prep -top Sbuffer_observed -flatten", "opt -full", "check -assert",
                   f"write_rtlil {WORK}/{side}_observed.il"]
        (WORK / f"{side}.ys").write_text("\n".join(script) + "\n")

    # Keep observation-history registers inside their consuming partitions.
    # Matching them would replace reset/query history with arbitrary inputs,
    # allowing observation of pipeline payloads before they are meaningful.
    (WORK / "sbuffer.eqy").write_text(f"""[gold]
read_rtlil {WORK}/base_observed.il
prep -top Sbuffer_observed

[gate]
read_rtlil {WORK}/tip_observed.il
prep -top Sbuffer_observed

[match *]
nodefault
gold-match clock
gold-match reset
gold-match io_*
gold-match dut.stateVec_*
gold-match dut.ptag_*
gold-match dut.vtag_*
gold-match dut.waitInflightMask_*
gold-match dut.cohCount_*
gold-match dut.missqReplayCount_*
gold-match dut.state_reg
gold-match dut.sbuffer_state
gold-match dut.enbufferSelReg
gold-match dut.dataModule.data_*
gold-match dut.dataModule.mask_*

[collect *]
""" + "\n".join(
        f"group dut.dataModule.{kind}_{entry}_{word}_*"
        for kind in ("data", "mask") for entry in range(16) for word in range(4)
    ) + """

[strategy local_sat]
use sat
depth 2
timeout 15

[strategy induction]
use sby
engine smtbmc z3
depth 4
timeout 60

[strategy pdr]
use sby
engine abc pdr
timeout 90
""")
    print(f"Wrote {WORK}/{{base,tip}}.ys, observation wrappers, and sbuffer.eqy")
    print("Next: yosys -s each .ys file, then eqy --setup to inspect partitions")


if __name__ == "__main__":
    main()
